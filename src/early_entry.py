"""Вход по ПЕРВОМУ актору против входа по конфлюенсу — парный замер.

ЗАЧЕМ. Аудит входа 11.08 на 13 689 сигналах показал, что каждый лишний актор стоит
денег. Парно, на одних и тех же токенах:

    n=2 против n=3  2901 токен  вход на 2: +$7129  на 3: −$1866  ожидание лучше 31%
    n=3 против n=4   908 токенов вход на 3: +$2452  на 4:   −$37  ожидание лучше 31%
    n=4 против n=5   333 токена  вход на 4: +$1049  на 5:   +$98  ожидание лучше 30%

Переход 2→3 занимает 29 секунд и делает вход дороже на 8.4%. Логика указывает, что
вход по ПЕРВОМУ актору ещё дешевле — но замерить это было нечем: трекер регистрирует
токен только после конфлюенса, а цена покупки в журнал не писалась. С 11.08 пишется.

ЧЕГО ЭТОТ ЗАМЕР НЕ ОТВЕЧАЕТ. Здесь сравниваются только токены, которые ВСЁ РАВНО
сложились в конфлюенс. Настоящий вход по одному актору брал бы и те, что не сложились
никогда, а по ним нет ни цены выхода, ни траектории — трекер их не ведёт. Поэтому
результат отвечает на вопрос «дешевле ли входить раньше на тех же токенах», а не
«стоит ли торговать каждую покупку актора». Второй вопрос требует отдельного сбора.

Run:  python -m src.early_entry [--горизонт 300]
"""
from __future__ import annotations

import argparse
import json
import statistics as st
from collections import defaultdict

from . import analysis, config

CLIP = 10.0
# измерено 10.08 на 179 живых сделках: вход тем дороже, чем больше купили до нас
ВЫХОД_И_КОМИССИИ = 0.058
ХАЙРКАТ_ВХОД = [(150, 0.046), (300, 0.067), (600, 0.086), (10 ** 9, 0.183)]


def хайркат(объём: float) -> float:
    for порог, вх in ХАЙРКАТ_ВХОД:
        if объём < порог:
            return вх + ВЫХОД_И_КОМИССИИ
    return ХАЙРКАТ_ВХОД[-1][1] + ВЫХОД_И_КОМИССИИ


def _траектории(нужны: set[str]) -> dict[str, list[tuple[float, float]]]:
    трек: dict[str, list] = defaultdict(list)
    p = config.OUTPUT_DIR / "price_history.jsonl"
    if not p.exists():
        return трек
    with open(p, encoding="utf-8") as f:
        for ln in f:
            if '"mint"' not in ln:
                continue
            try:
                r = json.loads(ln)
            except Exception:  # noqa: BLE001
                continue
            if r.get("mint") in нужны and r.get("price_usd"):
                трек[r["mint"]].append((r["ts"], r["price_usd"]))
    for v in трек.values():
        v.sort()
    return трек


def собрать(горизонт: float = 300.0) -> dict:
    """→ отчёт со сравнением. Пустой, если данных ещё мало."""
    # первая покупка каждого токена — из журнала покупок акторов (цена с 11.08)
    первая: dict[str, dict] = {}
    for r in analysis.read_jsonl("actor_buys.jsonl"):
        if not r.get("price") or not r.get("token_mint"):
            continue
        t = r["token_mint"]
        if t not in первая or r["ts"] < первая[t]["ts"]:
            первая[t] = r

    # момент конфлюенса — первый сигнал по токену
    сигнал: dict[str, dict] = {}
    for r in analysis.read_jsonl("signals.log"):
        s, m = r.get("signal"), r.get("market") or {}
        if not s or not m.get("price_usd"):
            continue
        t = s["token_mint"]
        if t not in сигнал or s["ts"] < сигнал[t]["ts"]:
            сигнал[t] = {"ts": s["ts"], "цена": m["price_usd"],
                         "объём": s.get("window_usd") or 0, "n": s["n_actors"]}

    общие = set(первая) & set(сигнал)
    трек = _траектории(общие)

    пары = []
    for t in общие:
        b, s = первая[t], сигнал[t]
        if b["ts"] > s["ts"]:            # покупка позже сигнала — это не первый вход
            continue
        точки = [p for ts, p in трек.get(t, []) if ts <= s["ts"] + горизонт]
        if not точки:
            continue
        конец = точки[-1]
        рано = конец / b["price"] - 1 - хайркат(b.get("usd") or 0)
        поздно = конец / s["цена"] - 1 - хайркат(s["объём"])
        пары.append({"tok": t, "рано": рано, "поздно": поздно,
                     "задержка": s["ts"] - b["ts"],
                     "дороже": s["цена"] / b["price"] - 1, "n": s["n"]})

    if len(пары) < 30:
        return {"пар": len(пары), "мало_данных": True}

    a = [x["рано"] for x in пары]
    c = [x["поздно"] for x in пары]
    sa, sc = sorted(a), sorted(c)
    return {
        "пар": len(пары), "мало_данных": False,
        "рано_сумма": sum(a) * CLIP, "поздно_сумма": sum(c) * CLIP,
        "рано_без_топ3": sum(sa[:-3]) * CLIP, "поздно_без_топ3": sum(sc[:-3]) * CLIP,
        "рано_медиана": st.median(a), "поздно_медиана": st.median(c),
        "рано_win": sum(1 for x in a if x > 0) / len(a),
        "поздно_win": sum(1 for x in c if x > 0) / len(c),
        "рано_лучше_доля": sum(1 for x, y in zip(a, c) if x > y) / len(пары),
        "медиана_задержки": st.median([x["задержка"] for x in пары]),
        "медиана_дороже": st.median([x["дороже"] for x in пары]),
    }


def отчёт(r: dict) -> str:
    if r.get("мало_данных"):
        return (f"ВХОД ПО ПЕРВОМУ АКТОРУ: данных пока мало — {r['пар']} пар "
                f"(нужно от 30). Журнал цены покупок пишется с 11.08, подождать ещё.")
    лучше = r["рано_сумма"] > r["поздно_сумма"]
    строки = [
        f"ВХОД ПО ПЕРВОМУ АКТОРУ против КОНФЛЮЕНСА · {r['пар']} парных токенов",
        "",
        f"по первому:   ${r['рано_сумма']:+.0f} · без топ-3 ${r['рано_без_топ3']:+.0f} · "
        f"медиана {r['рано_медиана']:+.1%} · win {r['рано_win']:.2f}",
        f"по конфлюенсу:${r['поздно_сумма']:+.0f} · без топ-3 ${r['поздно_без_топ3']:+.0f} · "
        f"медиана {r['поздно_медиана']:+.1%} · win {r['поздно_win']:.2f}",
        "",
        f"ранний вход лучше в {r['рано_лучше_доля']:.0%} случаев",
        f"цена ожидания: {r['медиана_задержки']:.0f}с, вход дороже на "
        f"{r['медиана_дороже']:+.1%}",
        "",
    ]
    if лучше and r["рано_без_топ3"] > r["поздно_без_топ3"]:
        строки.append("ВЫВОД: ранний вход выигрывает И по сумме, И без крайних сделок.")
        строки.append("ОГОВОРКА: сравнение только по токенам, которые ВСЁ РАВНО сложились "
                      "в конфлюенс. Торговать каждую покупку актора это не разрешает — "
                      "по несложившимся токенам данных нет вовсе.")
    elif лучше:
        строки.append("ВЫВОД: ранний вход лучше по сумме, но НЕ без крайних сделок — "
                      "держится на хвосте, решение откладывать до большей выборки.")
    else:
        строки.append("ВЫВОД: ранний вход НЕ лучше. Гипотеза не подтвердилась.")
    return "\n".join(строки)


def main() -> None:
    ap = argparse.ArgumentParser(description="Вход по первому актору против конфлюенса")
    ap.add_argument("--горизонт", type=float, default=300.0, help="сек удержания")
    ap.add_argument("--telegram", action="store_true", help="отправить итог в Telegram")
    a = ap.parse_args()
    r = собрать(a.горизонт)
    txt = отчёт(r)
    print(txt)
    if a.telegram:
        from . import delivery
        delivery.send_telegram("📊 " + txt)


if __name__ == "__main__":
    main()

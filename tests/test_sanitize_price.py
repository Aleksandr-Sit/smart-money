"""Защита от мусора источника цены — единственный барьер на путях «сделка» и
«запасная котировка» (у трекера свой такой же фильтр).

Случай 08.08, из-за которого функция вынесена под тест. Токен CgWJ5NBN… выпустился
с бондинг-кривой на DEX. Чтение кривой стало бессмысленным, фильтр трекера этот тик
корректно отбросил — и тем самым отправил монитор за запасной котировкой в Jupiter.
Jupiter в момент миграции пула отдал цену 4.7e-11 при последней честной 2.8e-05.
Проверки на этом пути не было. Трейлинг был взведён (пик 3.03x) и закрыл позицию
с −100%. Через 30 секунд реальная цена была 5.07x от входа.

Выпуск на DEX проходят 16.2% токенов — по определению лучшие из отслеживаемых.
"""
import pytest

from src.monitor import sanitize_price

JUMP = 50.0


def test_боевой_случай_выпуска_на_dex():
    """Точные числа из инцидента: обязана вернуться опорная цена, а не мусор."""
    out, anomaly = sanitize_price(4.709430239000689e-11, 2.7706e-05, JUMP)
    assert anomaly is True
    assert out == 2.7706e-05


def test_опорная_цена_а_не_none():
    """Вернуть None означало бы «цены нет» — выход сработал бы вслепую.
    Позиция должна продолжать оцениваться по последнему здравому значению."""
    out, _ = sanitize_price(1e-12, 1e-5, JUMP)
    assert out is not None
    assert out == 1e-5


def test_обычные_движения_проходят():
    """Фильтр не должен глушить нормальную волатильность мем-токена."""
    for price in (1.1e-5, 5e-5, 2e-6, 4.9e-4):      # от 0.2x до 49x
        out, anomaly = sanitize_price(price, 1e-5, JUMP)
        assert anomaly is False, f"{price:.1e} ошибочно признана аномалией"
        assert out == price


def test_срабатывает_в_обе_стороны():
    """Аномалия вверх ломала статистику раньше (цена $152 600 за токен),
    аномалия вниз ломает выходы. Ловим обе."""
    up, a_up = sanitize_price(1e-3, 1e-5, JUMP)      # 100x вверх
    dn, a_dn = sanitize_price(1e-7, 1e-5, JUMP)      # 100x вниз
    assert a_up and up == 1e-5
    assert a_dn and dn == 1e-5


def test_граница_порога():
    """Ровно на пороге — ещё не аномалия, за порогом — уже да."""
    assert sanitize_price(50e-5, 1e-5, JUMP)[1] is False    # ровно 50x
    assert sanitize_price(51e-5, 1e-5, JUMP)[1] is True


def test_без_опорной_цены_пропускаем():
    """Первая цена по токену сверять не с чем — не выдумываем аномалию."""
    out, anomaly = sanitize_price(1e-5, None, JUMP)
    assert anomaly is False and out == 1e-5
    out, anomaly = sanitize_price(1e-5, 0, JUMP)
    assert anomaly is False and out == 1e-5


@pytest.mark.parametrize("bad", [None, 0, -1e-5])
def test_мусор_на_входе(bad):
    """Отсутствующая или отрицательная цена — это не аномалия, а отсутствие данных."""
    assert sanitize_price(bad, 1e-5, JUMP) == (None, False)

"""Испытательный срок — тесты на отбор и на безопасность правки watchlist.

Замер 12.08 показал, зачем нужен подъём: кошелёк 2CQgjcdN имел ШЕСТЬ попаданий
в победителей и подъём 0.7x — у неудачников он встречался чаще. По одному счёту
попаданий он выглядел бы лучшей находкой списка.
"""
import json

import pytest

from src import probation as pr


def _к(адрес, побед, неудач, подъём, в_списке=False):
    return {"кошелёк": адрес, "победителей": побед, "неудачников": неудач,
            "подъём": подъём, "медиана_места": 5, "в_списке": в_списке}


def test_высокая_частота_без_подъёма_не_проходит():
    """2CQgjcdN: 6 победителей, 4 неудачника, подъём 0.7x — покупает всё подряд."""
    к = [_к("ЧАСТЫЙ", 6, 4, 0.7), _к("ОТБОРЩИК", 3, 0, 2.1)]
    из = pr.отобрать(к, мин_побед=3, мин_подъём=1.5, уже=set())
    assert [x["кошелёк"] for x in из] == ["ОТБОРЩИК"]


def test_мало_попаданий_не_проходит_даже_при_высоком_подъёме():
    """Одно попадание и ноль неудач дают красивый подъём и нулевую значимость."""
    из = pr.отобрать([_к("СЛУЧАЙНЫЙ", 1, 0, 3.0)], 3, 1.5, set())
    assert из == []


def test_без_подъёма_кандидат_не_проходит():
    """Подъём None означает, что контрольная группа не разобрана. Пускать таких
    в watchlist — то же самое, что не проверять вовсе."""
    из = pr.отобрать([_к("БЕЗ_КОНТРОЛЯ", 9, 0, None)], 3, 1.5, set())
    assert из == []


def test_уже_известный_кошелёк_не_дублируется():
    к = [_к("ЕСТЬ", 5, 0, 2.0), _к("НОВЫЙ", 5, 0, 2.0)]
    из = pr.отобрать(к, 3, 1.5, уже={"ЕСТЬ"})
    assert [x["кошелёк"] for x in из] == ["НОВЫЙ"]


def test_известные_видят_и_вложенные_кошельки():
    """Актор в watchlist — это ГРУППА кошельков, и адрес может лежать внутри
    wallets, а не в actor_id. Иначе один и тот же кошелёк попадёт в список дважды."""
    wl = [{"actor_id": "A1", "wallets": ["W1", "W2"]}]
    assert pr.известные(wl) == {"A1", "W1", "W2"}


def test_запись_помечена_испытательным_сроком():
    з = pr.запись(_к("НОВЫЙ", 4, 1, 1.9))
    assert з["испытательный_срок"] is True
    assert з["actor_id"] == "НОВЫЙ" and з["wallets"] == ["НОВЫЙ"]
    assert з["weight"] == 1.0, "занижать вес значило бы предрешить исход замера"
    assert з["победителей"] == 4 and з["подъём"] == 1.9


def test_применение_не_трогает_прежних():
    wl = [{"actor_id": "СТАРЫЙ", "wallets": ["СТАРЫЙ"]}]
    новый = pr.применить([_к("НОВЫЙ", 4, 0, 2.0)], wl)
    assert len(новый) == 2 and новый[0] == wl[0]


def test_сохранение_делает_резервную_копию(tmp_path, monkeypatch):
    """watchlist — вход стратегии. Откат должен быть возможен без git."""
    monkeypatch.setattr(pr.config, "OUTPUT_DIR", tmp_path)
    (tmp_path / pr.ФАЙЛ).write_text(json.dumps([{"actor_id": "СТАРЫЙ"}]), encoding="utf-8")
    pr.сохранить([{"actor_id": "СТАРЫЙ"}, {"actor_id": "НОВЫЙ"}])
    рез = json.loads((tmp_path / "flow_watchlist_before_probation.json").read_text(encoding="utf-8"))
    итог = json.loads((tmp_path / pr.ФАЙЛ).read_text(encoding="utf-8"))
    assert рез == [{"actor_id": "СТАРЫЙ"}]
    assert len(итог) == 2


def test_отчёт_напоминает_про_перезапуск():
    т = pr.отчёт([_к("НОВЫЙ", 4, 0, 2.0)], 84, True)
    assert "перезапуск" in т.lower()
    assert "история не является доводом" in т


def test_отчёт_при_пустом_отборе_объясняет_причину():
    assert "подходящих кандидатов нет" in pr.отчёт([], 83, False)

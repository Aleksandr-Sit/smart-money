"""Оценка акторов — тесты на поведение, а не на цифры.

Прежний рейтинг на модельной цене входа объявил лучшей когортой пару, которая на
честной цене теряет $1.15 на сделку. Тесты закрепляют то, что не должно сломаться:
вход не берётся по якорю сигнала, устойчивость отличается от суммы, а малая выборка
называется малой, а не выдаётся за оценку.
"""
import pytest

from src import actor_scorecard as sc


@pytest.fixture
def данные(monkeypatch):
    def подставить(сигналы, закрытые, трек):
        monkeypatch.setattr(sc.analysis, "read_jsonl",
                            lambda имя, directory=None: сигналы if имя == "signals.log" else [])
        monkeypatch.setattr(sc.analysis, "load_closed", lambda *a, **k: закрытые)
        monkeypatch.setattr(sc.analysis, "траектории", lambda нужны, **k: трек)
    return подставить


def _сиг(tok, акторы, ts=100.0):
    return {"signal": {"token_mint": tok, "ts": ts, "actors": акторы}}


def _закр(tok, exit_ts=400.0, entry_ts=100):
    return {"token_mint": tok, "entry_ts": entry_ts, "exit_ts": exit_ts, "realized_pnl": 0.0}


def _поток(n, множитель, акторы=("A",), начало=0):
    """n токенов, у каждого цена растёт в `множитель` раз от первого тика трекера."""
    с, з, т = [], [], {}
    for i in range(начало, начало + n):
        tok = f"T{i}"
        ts = 100.0 + i * 1000
        с.append(_сиг(tok, list(акторы), ts))
        з.append(_закр(tok, exit_ts=ts + 300, entry_ts=ts))
        т[tok] = [(ts, 9.99, "signal"),            # якорь = цена актора, входить нельзя
                  (ts + 15, 1.0, "curve"),
                  (ts + 300, множитель, "curve")]
    return с, з, т


def test_вход_не_берётся_по_якорю_сигнала(данные):
    """Якорь src='signal' — это цена актора. Вход по нему повторил бы исходный дефект:
    в примере он в 9.99 раз выше рынка, и любой исход выглядел бы катастрофой."""
    с, з, т = _поток(120, 2.0)
    данные(с, з, т)
    d = sc.собрать(издержки=0.0)
    assert d["мало_данных"] is False
    m = d["рейтинг"][0]
    assert m["на_сделку"] == pytest.approx(10.0), "2x от первого ТИКА, а не от якоря"


def test_издержки_вычитаются_мультипликативно(данные):
    с, з, т = _поток(120, 2.0)
    данные(с, з, т)
    m = sc.собрать(издержки=0.12)["рейтинг"][0]
    assert m["на_сделку"] == pytest.approx((2.0 * 0.88 - 1) * 10, rel=1e-6)


def test_хвостовой_актор_не_попадает_в_устойчивые(данные):
    """Три сделки делают весь плюс — это удача, а не источник."""
    с, з, т = _поток(120, 0.9)                   # сто двадцать убыточных
    с2, з2, т2 = _поток(3, 200.0, начало=900)    # и три огромных
    данные(с + с2, з + з2, {**т, **т2})
    d = sc.собрать(издержки=0.0, мин_сделок=40)
    m = d["рейтинг"][0]
    assert m["сум"] > 0, "по сумме актор в плюсе"
    assert m["без3"] < 0, "но без топ-3 в минусе"
    assert d["устойчивые"] == [], "и потому не считается устойчивым"


def test_устойчивый_актор_проходит(данные):
    с, з, т = _поток(120, 1.5)
    данные(с, з, т)
    d = sc.собрать(издержки=0.0)
    assert [m["актор"] for m in d["устойчивые"]] == ["A"]
    assert d["устойчивые"][0]["сег"] == 4


def test_малая_выборка_идёт_в_испытательный_срок(данные):
    """CkLT4ADy приходит первым в 89% случаев, но закрытых сделок у него мало —
    судить рано, и отчёт обязан говорить это прямо, а не молчать."""
    с, з, т = _поток(120, 1.5, акторы=("A",))
    с2, з2, т2 = _поток(10, 3.0, акторы=("НОВИЧОК",), начало=500)
    данные(с + с2, з + з2, {**т, **т2})
    d = sc.собрать(издержки=0.0, мин_сделок=40)
    assert [m["актор"] for m in d["испытание"]] == ["НОВИЧОК"]
    assert "ИСПЫТАТЕЛЬНЫЙ СРОК" in sc.отчёт(d)


def test_мало_данных_признаётся_честно(данные):
    с, з, т = _поток(5, 2.0)
    данные(с, з, т)
    d = sc.собрать()
    assert d["мало_данных"] is True
    assert "данных мало" in sc.отчёт(d)


def test_отчёт_несёт_оговорку_про_завышенный_уровень(данные):
    с, з, т = _поток(120, 1.5)
    данные(с, з, т)
    т_ = sc.отчёт(sc.собрать(издержки=0.0))
    assert "завышен" in т_ and "первому тику" in т_


def test_отчёт_предупреждает_что_чистка_списка_ничего_не_даёт(данные):
    """Замер 12.08: удаление худших ПОВЕРХ фильтра независимости даёт ровно ноль.
    Без этой строки следующий читатель рейтинга начнёт чистить watchlist зря."""
    с, з, т = _поток(120, 0.5)
    данные(с, з, т)
    d = sc.собрать(издержки=0.0)
    assert d["убыточные"], "актор с падающей ценой обязан попасть в убыточные"
    assert "РОВНО НОЛЬ" in sc.отчёт(d)

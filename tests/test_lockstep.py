"""Связки кошельков одного участника — тесты на ПОВЕДЕНИЕ, а не на цифры.

Замер 11.08: порог CONFLUENCE_N=2 закрывался двумя кошельками одного лица в 993
из 1007 его сигналов. Тесты закрепляют то, что должно сохраниться при любых правках:
связка находится обоими признаками, транзитивна, а отсутствие файла не меняет
прежнее поведение монитора.
"""
import json

import pytest

from src import lockstep as ls


def _сигнал(tok, акторы):
    return {"signal": {"token_mint": tok, "actors": акторы, "ts": 1.0}}


def _покупка(tok, актор, ts):
    return {"token_mint": tok, "actor": актор, "ts": ts}


@pytest.fixture
def журналы(monkeypatch):
    def подставить(сигналы=(), покупки=()):
        monkeypatch.setattr(ls.analysis, "read_jsonl",
                            lambda имя, directory=None: {
                                "signals.log": list(сигналы),
                                "actor_buys.jsonl": list(покупки)}.get(имя, []))
    return подставить


def test_совпадение_токенов_связывает(журналы):
    """Признак 1: два кошелька ходят по одним и тем же 50 токенам."""
    журналы(сигналы=[_сигнал(f"T{i}", ["A", "B"]) for i in range(50)])
    d = ls.построить(мин_токенов=40)
    assert d["группы"] == [["A", "B"]]


def test_разные_токены_не_связываются(журналы):
    с = [_сигнал(f"T{i}", ["A"]) for i in range(50)]
    с += [_сигнал(f"U{i}", ["B"]) for i in range(50)]
    журналы(сигналы=с)
    assert ls.построить(мин_токенов=40)["группы"] == []


def test_частичное_пересечение_ниже_порога_не_связывает(журналы):
    """Половина общих токенов — это два разных участника на одном рынке,
    а не один участник. Порог существует именно для этого случая."""
    с = [_сигнал(f"O{i}", ["A", "B"]) for i in range(50)]
    с += [_сигнал(f"a{i}", ["A"]) for i in range(50)]
    с += [_сигнал(f"b{i}", ["B"]) for i in range(50)]
    журналы(сигналы=с)
    assert ls.построить(мин_токенов=40)["группы"] == []


def test_совместная_покупка_в_пределах_секунды_связывает(журналы):
    """Признак 2 виден на десятке сделок — за 30 суток истории ждать не нужно."""
    п = []
    for i in range(12):
        п.append(_покупка(f"T{i}", "A", 1000.0 + i * 100))
        п.append(_покупка(f"T{i}", "B", 1000.2 + i * 100))   # +0.2с
    журналы(покупки=п)
    assert ls.построить()["группы"] == [["A", "B"]]


def test_покупка_позже_окна_не_связывает(журналы):
    п = []
    for i in range(12):
        п.append(_покупка(f"T{i}", "A", 1000.0 + i * 100))
        п.append(_покупка(f"T{i}", "B", 1030.0 + i * 100))   # +30с — обычный конфлюенс
    журналы(покупки=п)
    assert ls.построить()["группы"] == []


def test_связка_транзитивна(журналы):
    """Найденная в проде группа была из трёх кошельков: A~B и B~C дали A,B,C."""
    с = [_сигнал(f"T{i}", ["A", "B"]) for i in range(50)]
    с += [_сигнал(f"T{i}", ["B", "C"]) for i in range(50)]
    журналы(сигналы=с)
    assert ls.построить(мин_токенов=40)["группы"] == [["A", "B", "C"]]


def test_независимых_считает_группы_а_не_кошельки():
    карта = {"A": "A", "B": "A"}
    assert ls.независимых(["A", "B"], карта) == 1
    assert ls.независимых(["A", "B", "C"], карта) == 2


def test_без_файла_поведение_прежнее(tmp_path):
    """Нет файла связок → каждый кошелёк сам по себе. Отсутствие данных не должно
    молча менять правило входа."""
    assert ls.загрузить(tmp_path / "нет.json") == {}
    assert ls.независимых(["A", "B"], {}) == 2


def test_загрузка_сопоставляет_всех_членов_группы(tmp_path):
    p = tmp_path / "l.json"
    p.write_text(json.dumps({"группы": [["A", "B", "C"]]}), encoding="utf-8")
    карта = ls.загрузить(p)
    assert карта["A"] == карта["B"] == карта["C"]
    assert ls.независимых(["A", "C"], карта) == 1


def test_битый_файл_не_роняет_монитор(tmp_path):
    p = tmp_path / "l.json"
    p.write_text("{не json", encoding="utf-8")
    assert ls.загрузить(p) == {}


def test_отчёт_говорит_когда_связок_нет(журналы):
    журналы()
    assert "ни одной связки" in ls.отчёт(ls.построить())


def test_доля_совместных_не_превышает_единицу(журналы):
    """Первый прогон на проде дал долю 1.803 — считались пары событий, а докупка
    одного токена порождает несколько пар. Доля обязана считаться по ТОКЕНАМ."""
    п = []
    for i in range(12):
        for k in range(3):                      # каждый докупает токен трижды
            п.append(_покупка(f"T{i}", "A", 1000.0 + i * 100 + k * 0.01))
            п.append(_покупка(f"T{i}", "B", 1000.2 + i * 100 + k * 0.01))
    журналы(покупки=п)
    d = ls.построить()
    assert d["группы"] == [["A", "B"]]
    assert all(с[3] <= 1.0 for с in d["связки"]), "доля не может быть больше единицы"


def test_записи_выходов_не_считаются_сигналами(журналы):
    """deliver_exit пишет в signals.log — счётчик выборки не должен их учитывать."""
    журналы(сигналы=[_сигнал("T1", ["A"]), {"type": "exit", "token_mint": "T1"}])
    assert ls.построить()["сигналов"] == 1


def test_поле_независимых_попадает_в_журнал_сигналов(monkeypatch):
    """Без этого поля разделение «настоящий конфлюенс / ложный» пришлось бы каждый раз
    восстанавливать задним числом по signals.log."""
    from dataclasses import dataclass
    from src import delivery

    out = []
    monkeypatch.setattr(delivery, "_append", lambda p, o: out.append((p.name, o)))
    monkeypatch.setattr(delivery, "send_telegram", lambda *a, **k: None)

    @dataclass
    class _S:
        token_mint: str = "TOK"
        ts: float = 1.0
        actors: tuple = ("A", "B")
        n_actors: int = 2
        window_usd: float = 100.0
        strength: float = 1.0
        level: str = "weak"
        quiet: bool = False
        first_buy_ts: float = 0.0

    delivery.deliver(_S(), {"verdict": "ok"}, {"price_usd": 1.0}, True, False, независимых=1)
    рек = dict(out)["signals.log"]
    assert рек["независимых"] == 1
    assert рек["signal"]["n_actors"] == 2, "n_actors остаётся как был — правило не меняется"


def test_независимых_без_связок_равно_числу_кошельков():
    """Пока файла связок нет, поле обязано совпадать с n_actors — иначе отчётность
    начнёт расходиться с правилом входа без единой правки конфига."""
    assert ls.независимых(["A", "B"], {}) == 2

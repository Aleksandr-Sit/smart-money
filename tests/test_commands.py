"""Управление из Telegram — тесты на безопасность и на переживание перезапуска.

Четыре команды: /статус, /баланс, /стоп, /старт. Ничего, что двигает деньги.
Главные свойства, которые обязаны сохраниться при любых правках: чужой чат не
управляет ботом, а остановка входов не отменяется молча перезапуском контейнера.
"""
import json

import pytest

from src import commands as cm


@pytest.fixture(autouse=True)
def песочница(tmp_path, monkeypatch):
    monkeypatch.setattr(cm.config, "OUTPUT_DIR", tmp_path)
    return tmp_path


def _upd(текст, чат="555", uid=1):
    return {"update_id": uid, "message": {"chat": {"id": чат}, "text": текст}}


# ---------- безопасность ----------

def test_чужой_чат_не_управляет_ботом():
    """Имя бота публично: кто угодно может ему написать. Команда из чужого чата
    обязана быть неотличима от молчания."""
    assert cm._разобрать(_upd("/стоп", чат="999"), свой_чат="555") is None
    assert cm._разобрать(_upd("/стоп", чат="555"), свой_чат="555") == "стоп"


def test_чат_сравнивается_как_строка():
    """id приходит числом, а из .env читается строкой — сравнение типов уже ломало
    подобные проверки в других проектах."""
    assert cm._разобрать(_upd("/статус", чат=555), свой_чат="555") == "статус"


def test_неизвестный_текст_игнорируется():
    assert cm._разобрать(_upd("привет"), свой_чат="555") is None
    assert cm._разобрать(_upd("/вывести_всё"), свой_чат="555") is None


def test_команда_с_упоминанием_бота_распознаётся():
    """В группах Telegram дописывает @имя_бота."""
    assert cm._разобрать(_upd("/стоп@smartmoney_bot"), свой_чат="555") == "стоп"


def test_латинские_алиасы_работают():
    """Меню команд Telegram принимает только латиницу."""
    assert cm._разобрать(_upd("/stop"), свой_чат="555") == "стоп"
    assert cm._разобрать(_upd("/status"), свой_чат="555") == "статус"


def test_опасных_команд_нет():
    """Вывода средств, смены клипа и включения живого режима быть не должно."""
    сомнительные = [c for c in cm.АЛИАСЫ.values()
                    if c not in ("статус", "баланс", "стоп", "старт")]
    assert сомнительные == []


# ---------- пауза ----------

def test_пауза_переживает_перезапуск(песочница):
    """Флаг в файле, а не только в памяти: иначе владелец остановил торговлю,
    контейнер перезапустился — и входы молча возобновились."""
    assert cm.на_паузе() is False
    cm.выполнить("стоп", {})
    assert cm.на_паузе() is True
    assert json.loads((песочница / cm.ФАЙЛ_ПАУЗЫ).read_text(encoding="utf-8"))["paused"] is True
    cm.выполнить("старт", {})
    assert cm.на_паузе() is False


def test_битый_файл_паузы_не_останавливает_торговлю(песочница):
    """Нечитаемый файл не должен молча превращаться в остановку — это отказ
    в сторону бездействия, о котором никто не узнает."""
    (песочница / cm.ФАЙЛ_ПАУЗЫ).write_text("{не json", encoding="utf-8")
    assert cm.на_паузе() is False


def test_ответ_на_стоп_объясняет_судьбу_открытых_позиций():
    т = cm.выполнить("стоп", {})
    assert "открытые позиции" in т.lower() and "/старт" in т


# ---------- сбор ответов ----------

def test_сбой_обработчика_не_роняет_петлю():
    def падает():
        raise RuntimeError("узел лёг")
    assert "RuntimeError" in cm.выполнить("статус", {"статус": падает})


def test_неизвестная_команда_отвечает_понятно():
    assert cm.выполнить("чепуха", {}) == "неизвестная команда"


def test_опрос_без_настроек_телеграма_возвращает_none(monkeypatch):
    """Без TELEGRAM_* петлю надо гасить, а не крутить вхолостую каждые 25 секунд."""
    monkeypatch.setattr(cm.config, "secret", lambda имя, required=True: None)
    assert cm.опросить({}, None) == (None, False)


def test_offset_двигается_даже_на_чужих_сообщениях(monkeypatch):
    """Иначе чужое сообщение застрянет в очереди и будет перечитываться вечно."""
    monkeypatch.setattr(cm.config, "secret",
                        lambda имя, required=True: "555" if "CHAT" in имя else "t")
    monkeypatch.setattr(cm, "_послать", lambda *a: None)

    class _О:
        @staticmethod
        def json():
            return {"result": [_upd("привет", чат="999", uid=7)]}

    monkeypatch.setattr(cm.requests, "get", lambda *a, **k: _О())
    assert cm.опросить({}, None) == (8, True)


def test_пустой_опрос_не_гасит_петлю(monkeypatch):
    """Первая версия возвращала только offset, и None означал сразу «не настроен»
    и «обновлений нет» — петля команд убивала себя на первом же пустом опросе,
    то есть кнопки переставали работать навсегда и молча."""
    monkeypatch.setattr(cm.config, "secret",
                        lambda имя, required=True: "555" if "CHAT" in имя else "t")

    class _Пусто:
        @staticmethod
        def json():
            return {"result": []}

    monkeypatch.setattr(cm.requests, "get", lambda *a, **k: _Пусто())
    offset, настроен = cm.опросить({}, None)
    assert настроен is True, "пустой ответ не означает, что Telegram не настроен"
    assert offset is None

"""Настоящая цена круга, измеренная на живых деньгах (10.08).

Прежний EXIT_FEE 6% приходил из shadow-замера: медиана 3.3%, p90 4.2%, «запас 3.6x»
к порогу смерти edge в 12%. Shadow при этом мерил только фрикцию КОТИРОВКИ и не видел
главного — что модель записывает вход по цене, которую получил АКТОР, а не мы.

Разложение 179 живых сделок по дельтам самих транзакций:
    вход: купили дороже модели   медиана −5.66%  среднее −6.38%   62% разрыва
    выход: продали дешевле       медиана −3.50%  среднее −5.47%   38% разрыва
    комиссии сети                медиана −0.24%  среднее −0.30%
    ПОЛНЫЙ РАЗРЫВ                медиана −10.76% среднее −16.89%

Тест держит значение привязанным к замеру: молчаливый откат к «удобным» 6% сделал бы
всю накопленную статистику снова завышенной примерно на 11% на сделку.
"""
import pytest

from src import strategy

# что показал замер 10.08 — не менять без нового замера на живых деньгах
ЗАМЕР_ВХОД_СРЕДНЕЕ = 0.0638
ЗАМЕР_ВЫХОД_СРЕДНЕЕ = 0.0547
ЗАМЕР_КОМИССИИ = 0.0030
ЗАМЕР_СУММА = 0.1215         # сложение слагаемых — цена круга для типичной сделки
ЗАМЕР_РАЗРЫВ_СРЕДНЕЕ = 0.1689  # разница ДОХОДНОСТЕЙ, раздута хвостом (см. ниже)
ПОРОГ_СМЕРТИ = 0.12          # аудит-3: выше этого хайрката стратегия убыточна


def test_слагаемые_складываются_в_цену_круга():
    сумма = ЗАМЕР_ВХОД_СРЕДНЕЕ + ЗАМЕР_ВЫХОД_СРЕДНЕЕ + ЗАМЕР_КОМИССИИ
    assert сумма == pytest.approx(ЗАМЕР_СУММА, abs=0.002)


def test_средний_разрыв_БОЛЬШЕ_суммы_слагаемых_и_это_не_ошибка():
    """Ловушка, которую поймал этот же тест при первом написании.

    Сперва я поставил EXIT_FEE = 0.17 по среднему разрыву — и тест не сошёлся:
    6.38 + 5.47 + 0.30 = 12.15%, а разрыв показал 16.89%. Причина в том, что разрыв
    считается как разница ДОХОДНОСТЕЙ, а слагаемые входят мультипликативно:

        (1 + факт) = (1 + модель) × (1 + вход) × (1 + выход)

    На сделке с моделью +300% те же проценты дают втрое больший абсолютный разрыв.
    Поэтому среднее по разрывам раздуто хвостом, и вычитать его из КАЖДОЙ сделки
    значит наказывать типичную за чужой хвост.
    """
    assert ЗАМЕР_РАЗРЫВ_СРЕДНЕЕ > ЗАМЕР_СУММА


def test_цена_круга_соответствует_замеру():
    fee = strategy.RISK["EXIT_FEE"]
    assert fee >= 0.10, (
        f"EXIT_FEE={fee} заметно ниже измеренных {ЗАМЕР_СУММА:.1%}. Занижать эту "
        f"величину значит снова завышать всю статистику стратегии")
    assert fee <= 0.15, "выше измеренного — это уже не осторожность, а выдумка"


def test_вход_дороже_выхода():
    """Ключевой факт разложения: 62% разрыва даёт ВХОД, а не выход.

    Весь день чинился выход; замер показал, что течёт сильнее на входе. Тест
    фиксирует это, чтобы следующая попытка «улучшить результат» не начиналась
    заново с выхода.
    """
    assert ЗАМЕР_ВХОД_СРЕДНЕЕ > ЗАМЕР_ВЫХОД_СРЕДНЕЕ
    доля_входа = ЗАМЕР_ВХОД_СРЕДНЕЕ / (ЗАМЕР_ВХОД_СРЕДНЕЕ + ЗАМЕР_ВЫХОД_СРЕДНЕЕ)
    assert доля_входа == pytest.approx(0.54, abs=0.10)


def test_измеренная_цена_стоит_на_пороге_смерти():
    """Это не проверка кода, а закреплённый результат.

    Порог 12% назван аудитом-3 как граница, за которой стратегия убыточна.
    Измеренная цена круга 12.15% стоит ровно на нём — то есть edge съеден
    исполнением целиком. Если тест когда-нибудь упадёт, значит исполнение стало
    дешевле, и это надо заметить, а не проглядеть.
    """
    assert ЗАМЕР_СУММА >= ПОРОГ_СМЕРТИ, (
        "если цена круга опустилась ниже порога смерти — пересчитать стратегию "
        "и обновить этот тест новым замером")


def test_порог_влияния_на_цену_не_вводится():
    """Отрицательный результат, который стоит помнить.

    priceImpactPct от Jupiter НЕ предсказывает, дорого ли мы войдём: корреляция
    с входным разрывом −0.047 на 179 сделках. Ни один порог не улучшил итог, а
    корзина с НАИМЕНЬШИМ влиянием (0–0.5%) оказалась худшей: −$68 на 28 сделках,
    win 0.14 — нулевое влияние означает тощий или устаревший маршрут, а не хорошую
    ликвидность.
    """
    assert "MAX_PRICE_IMPACT" not in strategy.EXECUTION, (
        "порог влияния проверен и отвергнут замером — не вводить без нового")

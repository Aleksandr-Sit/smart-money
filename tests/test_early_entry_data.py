"""Цена в журнале покупок акторов — данные под единственный неизмеренный вход (11.08).

АУДИТ ВХОДА на 13 689 сигналах за 28.7 суток показал: каждый лишний актор стоит денег.
Парное сравнение на одних и тех же токенах, дошедших до обоих уровней:

    n=2 против n=3  2901 токен  вход на 2: +$7129  на 3: −$1866  ожидание лучше 31%
    n=3 против n=4   908 токенов вход на 3: +$2452  на 4:   −$37  ожидание лучше 31%
    n=4 против n=5   333 токена  вход на 4: +$1049  на 5:   +$98  ожидание лучше 30%

Цена ожидания измерена прямо: переход 2→3 занимает 29 секунд и делает вход дороже
на 8.4%. Механизм тот же, что в разложении разрыва: каждый следующий покупатель
двигает кривую перед нами.

Отсюда гипотеза, что вход по ПЕРВОМУ актору ещё дешевле. Проверить её было нечем:
трекер регистрирует токен только после конфлюенса, а цена покупки не записывалась.
Это поле закрывает дыру — но именно ПРОВЕРИТЬ, а не подтвердить: один актор без
подтверждения может оказаться шумом, и когортное качество способно обвалиться.
"""
import pytest

from src import delivery


def _записи(monkeypatch):
    out = []
    monkeypatch.setattr(delivery, "_append", lambda p, o: out.append((p.name, o)))
    return out


def test_цена_попадает_в_журнал(monkeypatch):
    out = _записи(monkeypatch)
    delivery.log_actor_buy("A", "W", "TOK", 123.45, 1000.0, False, 0, price=4.2e-06)
    имя, rec = out[0]
    assert имя == "actor_buys.jsonl"
    assert rec["price"] == pytest.approx(4.2e-06)
    assert rec["usd"] == pytest.approx(123.45)


def test_без_цены_поле_есть_и_равно_None(monkeypatch):
    """Цена может не посчитаться (нет base_amount) — поле обязано присутствовать,
    иначе анализ будет молча пропускать такие строки, не зная почему."""
    out = _записи(monkeypatch)
    delivery.log_actor_buy("A", "W", "TOK", 10.0, 1000.0, False, 0)
    assert "price" in out[0][1] and out[0][1]["price"] is None


def test_поля_нужные_для_парного_сравнения_на_месте(monkeypatch):
    """Чтобы сравнить вход по первому актору со входом по второму, нужны:
    токен (связать с сигналом), время (найти первую покупку), цена (посчитать исход)."""
    out = _записи(monkeypatch)
    delivery.log_actor_buy("A", "W", "TOK", 10.0, 1000.0, True, 2, price=1.0)
    rec = out[0][1]
    for поле in ("token_mint", "ts", "price", "actor", "converged", "n_actors"):
        assert поле in rec, f"без поля {поле} парное сравнение не собрать"


def test_ожидание_следующего_актора_дороже_на_каждом_уровне():
    """Закреплённый результат аудита, чтобы к нему не возвращались по интуиции.

    Соблазн «дождаться подтверждения третьим актором» выглядит разумно и
    опровергается тремя независимыми парами подряд.
    """
    пары = {2: (7129, -1866), 3: (2452, -37), 4: (1049, 98)}
    for n, (рано, поздно) in пары.items():
        assert рано > поздно, f"на уровне n={n} ожидание оказалось бы выгодным"

"""Алерт обязан соответствовать тому, что произошло (правка 11.08).

После перевода в бумажный режим владельцу за ночь ушли три тревоги, ни одна из
которых не была правдой:

    22:07  РАСХОЖДЕНИЕ: кошелёк изменился на +0.0000 SOL, учёт говорит −0.2541 SOL
    23:04  ТОРГОВЛЯ ОСТАНОВЛЕНА — дневной стоп: −$102.88 <= −$100.00
    00:07  РАСХОЖДЕНИЕ: кошелёк +0.0000 SOL, учёт +1.3262 SOL

Причины:
  1. сверка учёта с кошельком в БУМАЖНОМ режиме бессмысленна — кошелёк не двигается;
  2. в режиме shadow дневной стоп НЕ блокирует входы, он лишь помечает состояние,
     а сообщение утверждало обратное.

Алерт, который кричит о несуществующем, хуже отсутствующего: он приучает не верить
следующему.
"""
import pytest

from src import strategy


def test_в_бумажном_режиме_сверка_с_кошельком_не_имеет_смысла():
    """Кошелёк заморожен, счётчик растёт — расхождение неизбежно и не информативно."""
    живой = False
    кошелёк_сдвинулся = 0.0
    учёт_сдвинулся = -0.2541
    надо_ли_тревожить = живой and abs(кошелёк_сдвинулся - учёт_сдвинулся) > 0.15
    assert not надо_ли_тревожить


def test_в_живом_режиме_такое_расхождение_ТРЕВОГА():
    """Обратная сторона: в живом режиме ровно это и надо ловить."""
    живой = True
    надо_ли_тревожить = живой and abs(0.0 - (-0.2541)) > 0.15
    assert надо_ли_тревожить


@pytest.mark.parametrize("режим,ожидаем_слово", [
    ("enforce", "ОСТАНОВЛЕНА"),
    ("shadow", "на бумаге"),
])
def test_текст_стопа_зависит_от_режима(режим, ожидаем_слово):
    """В shadow стоп не режет поток — и говорить о нём надо иначе."""
    жёстко = режим == "enforce"
    текст = ("ТОРГОВЛЯ ОСТАНОВЛЕНА — дневной стоп" if жёстко else
             "на бумаге сработал бы дневной стоп (режим shadow: входы продолжаются)")
    assert ожидаем_слово in текст


def test_shadow_действительно_не_блокирует_входы():
    """Проверка не текста, а поведения: иначе формулировка была бы враньём наоборот."""
    from src import risk
    rm = risk.RiskManager(cfg={"RISK_MODE": "shadow"},
                          path=strategy.PATH.parent / "_alert_selftest.json")
    rm.state.halted = True
    rm.state.halt_reason = "дневной стоп: тест"
    можно, причина, блок = rm.gate(0)
    rm.path.unlink(missing_ok=True)
    assert можно is True, "в shadow денежный стоп обязан пропускать поток"
    assert блок is True, "но факт срабатывания должен фиксироваться"


def test_enforce_блокирует():
    from src import risk
    rm = risk.RiskManager(cfg={"RISK_MODE": "enforce"},
                          path=strategy.PATH.parent / "_alert_selftest2.json")
    rm.state.halted = True
    rm.state.halt_reason = "дневной стоп: тест"
    можно, _, _ = rm.gate(0)
    rm.path.unlink(missing_ok=True)
    assert можно is False, "с реальными деньгами стоп обязан резать"

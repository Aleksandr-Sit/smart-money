"""Парный замер «вход по первому актору против конфлюенса».

Считает на данных, которые начали собираться 11.08 (цена в actor_buys.jsonl).
Тесты проверяют не цифры, а поведение отчёта: он обязан честно признавать нехватку
данных и не выдавать хвостовой результат за устойчивый.
"""
import pytest

from src import early_entry as ee


@pytest.fixture
def данные(monkeypatch):
    """Подменяем оба журнала и траектории — сеть и диск не нужны."""
    def подставить(покупки, сигналы, трек):
        def _read(name, directory=None):
            return {"actor_buys.jsonl": покупки, "signals.log": сигналы}.get(name, [])
        monkeypatch.setattr(ee.analysis, "read_jsonl", _read)
        monkeypatch.setattr(ee, "_траектории", lambda нужны: трек)
    return подставить


def _покупка(tok, ts, price, usd=100.0):
    return {"token_mint": tok, "ts": ts, "price": price, "usd": usd}


def _сигнал(tok, ts, price, объём=200.0, n=2):
    return {"signal": {"token_mint": tok, "ts": ts, "n_actors": n, "window_usd": объём},
            "market": {"price_usd": price}}


def test_мало_данных_признаётся_честно(данные):
    данные([_покупка("A", 100, 1.0)], [_сигнал("A", 130, 1.1)],
           {"A": [(130, 1.1), (400, 1.5)]})
    r = ee.собрать()
    assert r["мало_данных"] is True
    assert "данных пока мало" in ee.отчёт(r)


def test_ранний_вход_дешевле_при_растущей_цене(данные):
    """Базовый случай: актор купил по 1.0, конфлюенс сложился по 1.1 — вход раньше
    даёт больше на том же выходе."""
    п, с, тр = [], [], {}
    for i in range(40):
        tok = f"T{i}"
        п.append(_покупка(tok, 100, 1.0))
        с.append(_сигнал(tok, 130, 1.1))
        тр[tok] = [(130, 1.1), (400, 1.5)]
    данные(п, с, тр)
    r = ee.собрать()
    assert r["мало_данных"] is False and r["пар"] == 40
    assert r["рано_сумма"] > r["поздно_сумма"]
    assert r["рано_лучше_доля"] == pytest.approx(1.0)
    assert r["медиана_дороже"] == pytest.approx(0.1, abs=0.01)
    assert "ВЫВОД: ранний вход выигрывает" in ee.отчёт(r)


def test_отчёт_отличает_хвостовой_выигрыш_от_устойчивого(данные):
    """Если преимущество держится на нескольких сделках, отчёт обязан это сказать,
    а не праздновать сумму. Тот же разбор без топ-3, что и во всех аудитах."""
    п, с, тр = [], [], {}
    for i in range(40):
        tok = f"T{i}"
        # объёмы РАВНЫ намеренно: иначе разницу решит хайркат, а не цена входа —
        # на этом тест и упал в первой версии
        рано_цена, поздно_цена = (1.0, 0.97) if i >= 3 else (0.2, 1.0)
        п.append(_покупка(tok, 100, рано_цена, usd=200.0))
        с.append(_сигнал(tok, 130, поздно_цена, объём=200.0))
        тр[tok] = [(130, поздно_цена), (400, 1.0)]
    данные(п, с, тр)
    r = ee.собрать()
    assert r["рано_сумма"] > r["поздно_сумма"], "по сумме ранний впереди"
    assert r["рано_без_топ3"] < r["поздно_без_топ3"], "но без топ-3 отстаёт"
    assert "держится на хвосте" in ee.отчёт(r)


def test_опровержение_тоже_проговаривается(данные):
    п, с, тр = [], [], {}
    for i in range(40):
        tok = f"T{i}"
        п.append(_покупка(tok, 100, 1.2))       # первая покупка ДОРОЖЕ
        с.append(_сигнал(tok, 130, 1.0))
        тр[tok] = [(130, 1.0), (400, 1.1)]
    данные(п, с, тр)
    assert "не подтвердилась" in ee.отчёт(ee.собрать())


def test_покупка_позже_сигнала_не_считается_первой(данные):
    """Актор мог докупить уже после конфлюенса — это не ранний вход."""
    п, с, тр = [], [], {}
    for i in range(40):
        tok = f"T{i}"
        п.append(_покупка(tok, 200, 1.0))       # позже сигнала
        с.append(_сигнал(tok, 130, 1.1))
        тр[tok] = [(130, 1.1), (400, 1.5)]
    данные(п, с, тр)
    assert ee.собрать()["мало_данных"] is True


def test_хайркат_растёт_с_объёмом():
    """Вход тем дороже, чем больше купили до нас — замер 10.08."""
    assert ee.хайркат(100) < ee.хайркат(200) < ee.хайркат(500) < ee.хайркат(5000)
    assert ee.хайркат(100) == pytest.approx(0.046 + ee.ВЫХОД_И_КОМИССИИ)


def test_оговорка_про_несложившиеся_токены_в_отчёте(данные):
    """Главное ограничение замера должно ехать вместе с выводом, а не остаться в коде."""
    п, с, тр = [], [], {}
    for i in range(40):
        tok = f"T{i}"
        п.append(_покупка(tok, 100, 1.0))
        с.append(_сигнал(tok, 130, 1.1))
        тр[tok] = [(130, 1.1), (400, 1.5)]
    данные(п, с, тр)
    assert "не сложившимся" in ee.отчёт(ee.собрать()) or \
           "несложившимся" in ee.отчёт(ee.собрать())

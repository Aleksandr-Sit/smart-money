#!/bin/bash
# ПЕРЕСЧЁТ СВЯЗОК КОШЕЛЬКОВ — раз в сутки, без участия человека.
#
# Считать связки в торговом процессе нельзя: это разбор ~15 МБ журналов, а монитор
# в это время обрабатывает поток сделок. Здесь пересчёт идёт отдельным вызовом, а
# монитор просто перечитывает `output/lockstep.json` в каждом пульсе — перезапуск
# ему НЕ нужен, поэтому задача безопасна для открытых позиций.
#
# Зачем вообще: замер 11.08 показал, что один участник держит несколько кошельков и
# в одиночку закрывает порог CONFLUENCE_N=2. Такими были 12.3% сигналов. Пока связки
# только считаются и пишутся в журнал — правило входа не меняется.
cd /opt/smart-money || exit 0

LOG=logs/lockstep.log
mkdir -p logs
echo "=== $(date -u) пересчёт связок ===" >> "$LOG"

OUT=$(docker compose exec -T monitor python -m src.lockstep --сохранить 2>&1)
echo "$OUT" >> "$LOG"

# новая группа — событие: появился участник, который сам себе подтверждение.
# Молчим, когда состав не изменился, иначе ежедневный шум обесценит сигнал.
ПРЕЖ=output/.lockstep_groups
НОВ=$(echo "$OUT" | grep -c '^  из ')
if [ -f "$ПРЕЖ" ] && [ "$(cat "$ПРЕЖ")" != "$НОВ" ]; then
  docker compose exec -T monitor python -c "
from src import delivery
delivery.send_alert('''состав связок кошельков изменился: было $(cat "$ПРЕЖ"), стало $НОВ групп''')
" >> "$LOG" 2>&1
fi
echo "$НОВ" > "$ПРЕЖ"

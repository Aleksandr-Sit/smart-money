#!/bin/bash
# ФОРВАРД-ПРОВЕРКА ФИЛЬТРА НЕЗАВИСИМОСТИ через 5 суток после включения (12.08).
#
# Включено по A/B на истории: +$167/сут против +$144 у прежнего "all", 4/4 отрезка,
# 88% потока. Форвард нужен потому, что A/B был на СВОИХ же данных, а совпадение
# ожидания с фактом — единственная проверка, которую нельзя подогнать.
#
# ЧТО ИМЕННО СРАВНИВАТЬ. Отклонённые сигналы не превращаются в позиции, и наивно
# кажется, что их исход не узнать. Но трекер регистрирует токен ДО проверки правила
# (monitor: tracker.register стоит раньше tradable), поэтому траектории отклонённых
# лежат в price_history.jsonl — контрфактический исход восстанавливается полностью.
# Считать надо именно так, иначе получится замер ёмкости по данным, уже отфильтрованным
# измеряемым ограничением.
cd /opt/smart-money || exit 0
START=20260817
TODAY=$(date -u +%Y%m%d)
[ "$TODAY" -lt "$START" ] && exit 0

STAMP=output/.reminder_independent_sent
[ -f "$STAMP" ] && exit 0

LOG=logs/independent.log
mkdir -p logs
echo "=== $(date -u) форвард-проверка фильтра независимости ===" >> "$LOG"

docker compose exec -T monitor python -c "
from src import delivery, strategy
delivery.send_telegram(
    'ФИЛЬТР НЕЗАВИСИМОСТИ работает 5 суток (включён 12.08, конфиг ' + strategy.VERSION + ').\n'
    'Пора сверить форвард с ожиданием A/B: +\$167/сут против +\$144 у прежнего правила.\n\n'
    'Считать по signals.log: у отклонённых сигналов поле независимых < 2, а траектории\n'
    'лежат в price_history.jsonl — трекер регистрирует токен ДО проверки правила.\n'
    'Сравнивать взятые и отклонённые на одном окне, с суммой без топ-3 и по 4 отрезкам.'
)" >> "$LOG" 2>&1

touch "$STAMP"
echo "напоминание отправлено" >> "$LOG"
